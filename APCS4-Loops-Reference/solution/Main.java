public class Main {
    public static void main(String[] args) {
        System.out.println("For loop");
        for (int index = 0; index < 10; index++) {
            System.out.println(index);
        }

        System.out.println("While loop");
        int index = 0;
        while (index < 10) {
            System.out.println(index);
            index++;
        }
    }
}
